#. Write a C program for calculation of average of physics, chemistry, math, English.
phy = int(input("enter your marks in phy : "))
maths = int(input("enter yor marks in maths : "))
chemistry = int(input("enter yor marks in chemistry : "))
english = int(input("enter yor marks in english : "))
average = (phy + maths + chemistry + english) / 4
print("the average is ", average)
